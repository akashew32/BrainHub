import type { ProgrammingLanguage, ProgrammingQuestion, ProgrammingTopic } from "@/lib/programming";

type FactDefinition = readonly [
  id: string,
  label: string,
  correct: string,
  distractors: readonly [string, string, string],
  explanation: string,
  code?: string,
];

const promptPatterns = [
  (label: string) => `Which statement about ${label} is correct?`,
  (label: string) => `A code review mentions ${label}. Which explanation is accurate?`,
  (label: string) => `Choose the rule that correctly describes ${label}.`,
  (label: string) => `Which answer would you give about ${label}?`,
  (label: string) => `What should a programmer remember about ${label}?`,
] as const;

function buildFactQuestions(
  language: ProgrammingLanguage,
  topic: ProgrammingTopic,
  facts: readonly FactDefinition[],
): ProgrammingQuestion[] {
  return facts.flatMap(([id, label, correct, distractors, explanation, code]) =>
    promptPatterns.map((makePrompt, variant) => {
      const answer = variant % 4;
      const choices = [...distractors];
      choices.splice(answer, 0, correct);
      return {
        id: `${language}-${topic}-${id}-${variant + 1}`,
        concept: `${language}-${topic}-${id}`,
        topic,
        prompt: makePrompt(label),
        code,
        choices: choices as [string, string, string, string],
        answer,
        explanation,
      };
    }),
  );
}

